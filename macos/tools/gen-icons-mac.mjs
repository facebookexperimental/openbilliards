// R15; constitution P-VI: repo-owned, license-clean assets only).
//
//   node macos/tools/gen-icons-mac.mjs            # (re)generate the committed set
//   node macos/tools/gen-icons-mac.mjs --verify   # byte-compare against disk
//
// The brand SOURCE is ios/tools/appicon.svg — consumed strictly by
// REFERENCE: parsed at run time, never copied and never edited (the iOS
// generator ios/tools/gen-icons.mjs owns that file; regenerating there and
// re-running this tool keeps the mac set in lockstep). This tool renders
// the parsed scene (Slate Void canvas, Ball Ivory disc, Ivory Muted
// lower-left crescent — design register) into the macOS
// AppIcon.appiconset (16/32/128/256/512 pt @1x/@2x) committed under
// macos/App/Resources/Assets.xcassets.
//
// Unlike iOS, macOS does NOT mask app icons at display time, so the scene
// is composited onto the standard macOS icon-grid plate: a rounded
// rectangle of 824/1024 canvas side with corner radius 185.4/1024 (the
// Apple HIG app-icon grid), transparent outside. Rasterization is analytic
// (signed-distance coverage, 1px edge AA) and PNGs are encoded by a
// self-contained RGBA writer, so regeneration is deterministic: same
// inputs -> byte-identical outputs (T008 gate: run twice, hashes equal).

import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import zlib from 'node:zlib';

const TOOLS_DIR = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(TOOLS_DIR, '..', '..');
const SVG_PATH = path.join(ROOT, 'ios', 'tools', 'appicon.svg');
const XCASSETS = path.join(ROOT, 'macos', 'App', 'Resources', 'Assets.xcassets');
const APPICONSET = path.join(XCASSETS, 'AppIcon.appiconset');

// macOS icon-grid plate (fraction of the canvas): rounded-rect side and
// corner radius from Apple's 1024pt app-icon template.
const PLATE = { side: 824 / 1024, radius: 185.4 / 1024 };

// Required macOS AppIcon sizes (idiom `mac`). Renders are deduplicated by
// pixel size; catalog entries share files (16@2x == 32@1x, ...).
const ICON_ENTRIES = [
  { size: 16, scale: 1 }, { size: 16, scale: 2 },
  { size: 32, scale: 1 }, { size: 32, scale: 2 },
  { size: 128, scale: 1 }, { size: 128, scale: 2 },
  { size: 256, scale: 1 }, { size: 256, scale: 2 },
  { size: 512, scale: 1 }, { size: 512, scale: 2 },
];

// ---------------------------------------------------------------------------
// Brand-source parser: the SVG is generated by ios/tools/gen-icons.mjs with
// fixed formatting — a square viewBox, one background <rect>, the shade
// circle, its clipPath twin, and the clipped ball circle. Any structural
// drift fails LOUDLY here (never silently rendering a wrong brand).
function fail(msg) {
  console.error(`gen-icons-mac FAIL: ${msg}`);
  process.exit(1);
}
function hexToRgb(hex) {
  return [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16));
}
function parseBrandSvg(text) {
  const vb = text.match(/viewBox="0 0 (\d+) (\d+)"/);
  if (!vb || vb[1] !== vb[2]) fail(`${SVG_PATH}: expected a square viewBox`);
  const S = Number(vb[1]);
  const rect = text.match(/<rect width="\d+" height="\d+" fill="#([0-9a-f]{6})"\/>/);
  if (!rect) fail(`${SVG_PATH}: expected the background <rect fill="#rrggbb"/>`);
  const circles = [...text.matchAll(
    /<circle cx="([\d.]+)" cy="([\d.]+)" r="([\d.]+)"(?: fill="#([0-9a-f]{6})")?( clip-path="url\(#[^"]+\)")?\/>/g,
  )].map((m) => ({
    cx: Number(m[1]) / S, cy: Number(m[2]) / S, r: Number(m[3]) / S,
    fill: m[4] ? hexToRgb(m[4]) : null, clipped: Boolean(m[5]),
  }));
  const shade = circles.find((c) => c.fill && !c.clipped);
  const ball = circles.find((c) => c.fill && c.clipped);
  const clip = circles.find((c) => !c.fill);
  if (circles.length !== 3 || !shade || !ball || !clip) {
    fail(`${SVG_PATH}: expected exactly shade + clipPath + clipped ball circles`);
  }
  if (clip.cx !== shade.cx || clip.cy !== shade.cy || clip.r !== shade.r) {
    fail(`${SVG_PATH}: clipPath circle must equal the shade circle`);
  }
  return { bg: hexToRgb(rect[1]), shade, ball };
}

// ---------------------------------------------------------------------------
// Raster: analytic signed-distance coverage per pixel, 1px edge AA. The
// scene's unit square maps onto the plate rect; alpha is the plate
// coverage (straight/unassociated, per PNG). Fully transparent pixels are
// zeroed so output bytes are a pure function of the inputs.
function renderPixels(px, scene) {
  const { bg, shade, ball } = scene;
  const shadeRgb = shade.fill; const ballRgb = ball.fill;
  const center = px / 2;
  const half = (PLATE.side * px) / 2;
  const rad = PLATE.radius * px;
  const o = center - half; // plate origin; plate side = 2 * half
  const s = PLATE.side * px;
  const c1x = o + shade.cx * s; const c1y = o + shade.cy * s; const r1 = shade.r * s;
  const c2x = o + ball.cx * s; const c2y = o + ball.cy * s; const r2 = ball.r * s;
  const cov = (d) => Math.min(1, Math.max(0, 0.5 - d));
  const rgba = new Uint8Array(px * px * 4);
  for (let y = 0; y < px; y++) {
    for (let x = 0; x < px; x++) {
      const pxc = x + 0.5; const pyc = y + 0.5;
      // Rounded-rect signed distance (exact, componentwise corner form).
      const qx = Math.abs(pxc - center) - (half - rad);
      const qy = Math.abs(pyc - center) - (half - rad);
      const d = Math.min(Math.max(qx, qy), 0)
        + Math.hypot(Math.max(qx, 0), Math.max(qy, 0)) - rad;
      const a = cov(d);
      if (a === 0) continue; // leave the pixel zeroed
      const c1 = cov(Math.hypot(pxc - c1x, pyc - c1y) - r1);
      const c2 = Math.min(c1, cov(Math.hypot(pxc - c2x, pyc - c2y) - r2));
      const off = (y * px + x) * 4;
      for (let ch = 0; ch < 3; ch++) {
        rgba[off + ch] = Math.round(
          bg[ch] + (shadeRgb[ch] - bg[ch]) * c1 + (ballRgb[ch] - shadeRgb[ch]) * c2,
        );
      }
      rgba[off + 3] = Math.round(a * 255);
    }
  }
  return rgba;
}

// Minimal PNG encoder: 8-bit truecolor + alpha (type 6), filter None.
const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = (c & 1) ? (0xedb88320 ^ (c >>> 1)) : (c >>> 1);
    t[n] = c >>> 0;
  }
  return t;
})();
function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const out = Buffer.alloc(12 + data.length);
  out.writeUInt32BE(data.length, 0);
  out.write(type, 4, 'ascii');
  data.copy(out, 8);
  out.writeUInt32BE(crc32(out.subarray(4, 8 + data.length)), 8 + data.length);
  return out;
}
function encodePng(px, rgba) {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(px, 0); ihdr.writeUInt32BE(px, 4);
  ihdr[8] = 8; ihdr[9] = 6; // bit depth 8, color type 6 (RGBA)
  const raw = Buffer.alloc(px * (1 + px * 4));
  for (let y = 0; y < px; y++) {
    raw[y * (1 + px * 4)] = 0; // filter None
    Buffer.from(rgba.buffer, y * px * 4, px * 4).copy(raw, y * (1 + px * 4) + 1);
  }
  const idat = zlib.deflateSync(raw, { level: 9, memLevel: 9, strategy: zlib.constants.Z_DEFAULT_STRATEGY });
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk('IHDR', ihdr), chunk('IDAT', idat), chunk('IEND', Buffer.alloc(0)),
  ]);
}

// ---------------------------------------------------------------------------
function buildOutputs() {
  const scene = parseBrandSvg(fs.readFileSync(SVG_PATH, 'utf8'));
  const outputs = new Map(); // abs path -> Buffer
  outputs.set(path.join(XCASSETS, 'Contents.json'),
    Buffer.from(`${JSON.stringify({ info: { author: 'xcode', version: 1 } }, null, 2)}\n`));

  const pxOf = (e) => Math.round(e.size * e.scale);
  const uniquePx = [...new Set(ICON_ENTRIES.map(pxOf))].sort((a, b) => a - b);
  for (const px of uniquePx) {
    outputs.set(path.join(APPICONSET, `icon-${px}.png`), encodePng(px, renderPixels(px, scene)));
  }
  const images = ICON_ENTRIES.map((e) => ({
    filename: `icon-${pxOf(e)}.png`,
    idiom: 'mac',
    scale: `${e.scale}x`,
    size: `${e.size}x${e.size}`,
  }));
  outputs.set(path.join(APPICONSET, 'Contents.json'),
    Buffer.from(`${JSON.stringify({ images, info: { author: 'xcode', version: 1 } }, null, 2)}\n`));
  return outputs;
}

const verifyMode = process.argv.includes('--verify');
const outputs = buildOutputs();
let deltas = 0;
for (const [abs, buf] of outputs) {
  const rel = path.relative(ROOT, abs);
  if (verifyMode) {
    const onDisk = fs.existsSync(abs) ? fs.readFileSync(abs) : null;
    if (onDisk === null || !onDisk.equals(buf)) {
      console.error(`DELTA  ${rel}${onDisk === null ? ' (missing)' : ''}`);
      deltas++;
    }
  } else {
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, buf);
    console.log(`wrote  ${rel}  sha256:${createHash('sha256').update(buf).digest('hex').slice(0, 16)}`);
  }
}
if (verifyMode) {
  if (deltas > 0) {
    console.error(`verify FAIL: ${deltas} file(s) differ from a fresh render`);
    process.exit(1);
  }
  console.log(`verify OK: ${outputs.size} files byte-identical to a fresh render`);
} else {
  console.log(`generate OK: ${outputs.size} files`);
}
