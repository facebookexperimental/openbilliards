"""Silhouette overlays (port of Task C overlays.py; unchanged): model (cyan) vs ours (magenta), overlap white, on dark.
1 px = 1 mm for the three main views (same pixel mapping as the model silhouettes); zooms at 4 px/mm (pocket plans) and
2 px/mm (leg+cabinet elevation). Model masks are read from <out>/model/silhouettes (regenerated by silhouettes_model.py).
Output: <out>/overlays/*.png, <out>/data/silhouettes_ours/{view}_{family}.npy, <out>/data/overlay_index.json."""
