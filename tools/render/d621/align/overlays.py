FONT_PATH = "/System/Library/Fonts/Helvetica.ttc"


def _font(size):
    try:
        return ImageFont.truetype(FONT_PATH, size)
    except OSError:
        return ImageFont.load_default()


VIEWS = {  # axes (h,v), window
    "top":  dict(axes=(0, 1), x0=-1400.0, x1=1400.0, y0=-800.0, y1=800.0),
    "side": dict(axes=(0, 2), x0=-1400.0, x1=1400.0, y0=-20.0, y1=880.0),
    "end":  dict(axes=(1, 2), x0=-800.0, x1=800.0, y0=-20.0, y1=880.0),
}
ZOOMS = [
    ("corner_pocket_plan_all",      dict(axes=(0, 1), x0=1000.0, x1=1350.0, y0=425.0, y1=775.0), 4.0, families.MODEL_SIL_INCLUDE, families.OURS_SIL_INCLUDE, ("X", "Y")),
    ("corner_pocket_plan_abovebed", dict(axes=(0, 1), x0=1000.0, x1=1350.0, y0=425.0, y1=775.0), 4.0, families.ABOVE_BED_MODEL, families.ABOVE_BED_OURS, ("X", "Y")),
    ("side_pocket_plan_all",        dict(axes=(0, 1), x0=-175.0, x1=175.0, y0=450.0, y1=800.0), 4.0, families.MODEL_SIL_INCLUDE, families.OURS_SIL_INCLUDE, ("X", "Y")),
    ("side_pocket_plan_abovebed",   dict(axes=(0, 1), x0=-175.0, x1=175.0, y0=450.0, y1=800.0), 4.0, families.ABOVE_BED_MODEL, families.ABOVE_BED_OURS, ("X", "Y")),
    ("leg_cabinet_side_elev",       dict(axes=(0, 2), x0=800.0, x1=1400.0, y0=-20.0, y1=880.0), 2.0, families.MODEL_SIL_INCLUDE, families.OURS_SIL_INCLUDE, ("X", "Z")),
    ("leg_cabinet_end_elev",        dict(axes=(1, 2), x0=250.0, x1=800.0, y0=-20.0, y1=880.0), 2.0, families.MODEL_SIL_INCLUDE, families.OURS_SIL_INCLUDE, ("Y", "Z")),
]
CY = np.array([0, 190, 255], np.uint8); MG_ = np.array([255, 40, 200], np.uint8); WH = np.array([245, 245, 245], np.uint8); BG = np.array([14, 18, 24], np.uint8)


def raster(meshlist, view, scale=1.0):
    a, b = view["axes"]; W = int(round((view["x1"] - view["x0"]) * scale)); H = int(round((view["y1"] - view["y0"]) * scale))
    img = Image.new("1", (W, H), 0); dr = ImageDraw.Draw(img)
    for (Vv, Fv) in meshlist:
        h = Vv[:, a]; v = Vv[:, b]
        P = np.stack([(h - view["x0"]) * scale, (view["y1"] - v) * scale], axis=1)
        tri = Fv
        inside = ~(((P[tri, 0] < 0).all(1)) | ((P[tri, 0] > W).all(1)) | ((P[tri, 1] < 0).all(1)) | ((P[tri, 1] > H).all(1)))
        for t in tri[inside]:
            dr.polygon([tuple(P[i]) for i in t], fill=1, outline=1)
    return np.array(img, dtype=bool)


def compose(M, O, view, scale, grid_mm=100):
    H, W = M.shape; rgb = np.empty((H, W, 3), np.uint8); rgb[:] = BG
    rgb[M & ~O] = CY; rgb[O & ~M] = MG_; rgb[M & O] = WH
    g = np.zeros((H, W), bool)
    for xg in np.arange(np.ceil(view["x0"] / grid_mm) * grid_mm, view["x1"] + 1e-6, grid_mm):
        c = int(round((xg - view["x0"]) * scale))
        if 0 <= c < W: g[:, c] = True
    for yg in np.arange(np.ceil(view["y0"] / grid_mm) * grid_mm, view["y1"] + 1e-6, grid_mm):
        r = int(round((view["y1"] - yg) * scale))
        if 0 <= r < H: g[r, :] = True
    rgb[g] = (0.65 * rgb[g] + 0.35 * np.array([150, 150, 160])).astype(np.uint8)
    c0 = int(round((0 - view["x0"]) * scale)); r0 = int(round((view["y1"] - 0) * scale))
    if 0 <= c0 < W: rgb[:, c0] = (0.5 * rgb[:, c0] + 0.5 * np.array([200, 200, 210])).astype(np.uint8)
    if 0 <= r0 < H: rgb[r0, :] = (0.5 * rgb[r0, :] + 0.5 * np.array([200, 200, 210])).astype(np.uint8)
    return rgb


def extents(mask, view, scale):
    ys, xs = np.nonzero(mask)
    if len(xs) == 0: return None
    return (xs.min() / scale + view["x0"], (xs.max() + 1) / scale + view["x0"], view["y1"] - (ys.max() + 1) / scale, view["y1"] - ys.min() / scale)


def annotate(rgb, M, O, view, scale, title, labels, grid_mm=100):
    FONT = _font(22); FONT_B = _font(28)
    H, W, _ = rgb.shape; MARG_B = 150; MARG_R = 230; MARG_T = 100
    canvas = Image.new("RGB", (W + MARG_R, H + MARG_B + MARG_T), tuple(int(c) for c in BG)); canvas.paste(Image.fromarray(rgb), (0, MARG_T)); dr = ImageDraw.Draw(canvas)
    dr.text((10, 12), title, fill=(235, 235, 235), font=FONT_B)
    lx = 10; ly = 58
    dr.rectangle([lx, ly, lx + 24, ly + 24], fill=tuple(CY)); dr.text((lx + 32, ly), "model (purchased)", fill=(230, 230, 230), font=FONT)
    dr.rectangle([lx + 250, ly, lx + 274, ly + 24], fill=tuple(MG_)); dr.text((lx + 282, ly), "ours", fill=(230, 230, 230), font=FONT)
    dr.rectangle([lx + 370, ly, lx + 394, ly + 24], fill=tuple(WH)); dr.text((lx + 402, ly), "overlap", fill=(230, 230, 230), font=FONT)
    dr.text((lx + 520, ly), f"grid {grid_mm} mm   {scale:g} px/mm   axes through the origin brighter", fill=(180, 180, 190), font=FONT)
    hl, vl = labels
    for k, (mask, col, name) in enumerate(((M, tuple(CY), "model"), (O, tuple(MG_), "ours"))):
        e = extents(mask, view, scale)
        if e is None: continue
        x0, x1, y0, y1 = e
        yy = H + MARG_T + 30 + k * 50; cx0 = (x0 - view["x0"]) * scale; cx1 = (x1 - view["x0"]) * scale
        dr.line([cx0, yy, cx1, yy], fill=col, width=2); dr.line([cx0, yy - 10, cx0, yy + 10], fill=col, width=2); dr.line([cx1, yy - 10, cx1, yy + 10], fill=col, width=2)
        dr.text(((cx0 + cx1) / 2 - 120, yy + 6), f"{name} {hl}: {x1 - x0:.1f} mm  ({x0:.1f} .. {x1:.1f})", fill=(235, 235, 235), font=FONT)
        xx = W + 30 + k * 95; ry0 = MARG_T + (view["y1"] - y1) * scale; ry1 = MARG_T + (view["y1"] - y0) * scale
        dr.line([xx, ry0, xx, ry1], fill=col, width=2); dr.line([xx - 10, ry0, xx + 10, ry0], fill=col, width=2); dr.line([xx - 10, ry1, xx + 10, ry1], fill=col, width=2)
        label = f"{name} {vl}: {y1 - y0:.1f} mm ({y0:.1f} .. {y1:.1f})"; tw = int(FONT.getlength(label)) + 8
        txt = Image.new("RGB", (tw, 30), tuple(int(c) for c in BG)); ImageDraw.Draw(txt).text((4, 2), label, fill=(235, 235, 235), font=FONT)
        txt = txt.rotate(90, expand=True); py = int((ry0 + ry1) / 2 - txt.height / 2); py = max(MARG_T, min(py, canvas.height - txt.height)); canvas.paste(txt, (xx + 8, py))
    return canvas


def run(cfg, ours, OG, nodes, MG, log=print):
    OUT = cfg.overlays; DAT = cfg.sil_ours; os.makedirs(OUT, exist_ok=True); os.makedirs(DAT, exist_ok=True)
    def model_meshes(groups): return [(nodes[n]["V"], nodes[n]["F"]) for g in groups for n in MG.get(g, [])]
    def ours_meshes(groups): return [(ours[n]["V"], ours[n]["F"]) for g in groups for n in OG.get(g, [])]
    index = []
    for vname, view in VIEWS.items():
        Mm = {}
        for g in families.MODEL_SIL_INCLUDE:
            p = f"{cfg.model_sil}/{vname}_{g}.npy"
            if os.path.exists(p): Mm[g] = np.load(p)
        M = np.zeros_like(next(iter(Mm.values())))
        for g in Mm: M |= Mm[g]
        O = np.zeros_like(M)
        for g in families.OURS_SIL_INCLUDE:
            m = raster(ours_meshes([g]), view, 1.0); np.save(f"{DAT}/{vname}_{g}.npy", m); O |= m
        np.save(f"{DAT}/{vname}_all.npy", O)
        rgb = compose(M, O, view, 1.0)
        Image.fromarray(rgb).save(f"{OUT}/{vname}_overlay_1px_per_mm.png")
        lab = {"top": ("X (length)", "Y (width)"), "side": ("X (length)", "Z (height)"), "end": ("Y (width)", "Z (height)")}[vname]
        annotate(rgb, M, O, view, 1.0, f"{vname.upper()} view  -  model vs ours (Diamond Pro-Am 8 ft, registered on bed plane + plan centre)", lab).save(f"{OUT}/{vname}_overlay_annotated.png")
        inter = int((M & O).sum()); um = int(M.sum()); uo = int(O.sum()); uni = int((M | O).sum())
        index.append(dict(view=vname, px_per_mm=1.0, window=dict(h=[view["x0"], view["x1"]], v=[view["y0"], view["y1"]]), model_px=um, ours_px=uo, overlap_px=inter, union_px=uni, iou=round(inter / uni, 4), model_only_px=um - inter, ours_only_px=uo - inter,
                          model_extent=extents(M, view, 1.0), ours_extent=extents(O, view, 1.0),
                          file=f"{OUT}/{vname}_overlay_1px_per_mm.png", annotated=f"{OUT}/{vname}_overlay_annotated.png"))
        log(f"[overlays] {vname} IoU {round(inter / uni, 4)} model-only {um - inter} ours-only {uo - inter}")
    for name, view, sc, mg, og, lab in ZOOMS:
        M = raster(model_meshes(mg), view, sc); O = raster(ours_meshes(og), view, sc)
        rgb = compose(M, O, view, sc, grid_mm=50 if sc >= 4 else 100)
        Image.fromarray(rgb).save(f"{OUT}/zoom_{name}_{sc:g}px_per_mm.png")
        annotate(rgb, M, O, view, sc, f"ZOOM {name}  ({sc:g} px/mm)", lab, grid_mm=50 if sc >= 4 else 100).save(f"{OUT}/zoom_{name}_annotated.png")
        inter = int((M & O).sum()); uni = int((M | O).sum())
        index.append(dict(view=name, px_per_mm=sc, window=dict(h=[view["x0"], view["x1"]], v=[view["y0"], view["y1"]]), model_groups=mg, ours_groups=og, model_px=int(M.sum()), ours_px=int(O.sum()), overlap_px=inter, union_px=uni, iou=round(inter / uni, 4),
                          model_extent=extents(M, view, sc), ours_extent=extents(O, view, sc), file=f"{OUT}/zoom_{name}_{sc:g}px_per_mm.png", annotated=f"{OUT}/zoom_{name}_annotated.png"))
        log(f"[overlays] {name} IoU {round(inter / uni, 4)}")
    common.dump_json(index, os.path.join(cfg.data, "overlay_index.json"))
    return index


if __name__ == "__main__":
    cfg, _ = paths.from_args(description=__doc__)
    d, ours = common.load_ours(cfg.ours); OG = common.ours_groups(ours)
    nodes, MG = common.load_model(cfg.model_obj_dir)
    run(cfg, ours, OG, nodes, MG)
