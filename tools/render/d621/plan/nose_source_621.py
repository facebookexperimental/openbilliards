"""Bind the owner-selected Rasson CU-09 receipt, Diamond leaves and served leaf.

The scalar receipt is sufficient: never load or remeasure purchased Rasson
geometry. Run --write after deliberately updating the definitions, then --check.
The generated module's digest is part of table.js's import URL, so changing the
leaf also invalidates the existing f ruling's renderer binding.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[4]
SOURCE_PATH = "tools/render/d621/law/rasson_nose_source_621.json"
MODULE_PATH = "web/scene/diamondproam_nose.js"
TABLE_PATH = "web/scene/table.js"
LAW_PATH = "tools/render/d621/law/cushion_law_621.json"
SIZES = ("9ft", "8ft", "7ft")
CITATION = "rasson-ox-9ft CU-09, owner ruling 2026-09-10 option b"
# MODEL: immutable identities of the owner's specified cross-model source.
SOURCE_ID = dict(
    commit="d058e15c27bd03518ebae8a1fd0b439a817011f3",
    definition_path="docs/geometry/rasson-ox-9ft-table-definition.json",
    definition_sha256="f9170dd52129cab67d62453b1529d22a31394614774653b4b83c3e03af00ad99",
    leaf="CU-09", value_path="value.tip_fillet_R_mm",
    leaf_sha256="852a167245cb020c0505d781016cc1c1e3e7a65b1971976fff7b308a3fbcf709",
    record_path="docs/geometry/rasson-ox-9ft-a1-station-records.json",
    record_file_sha256="cbd1b30a51674bffa82b15e052d40264ca23b32a78732ed0d2074cd00ca683bc",
    record_pointer="/records/CU-09",
    record_sha256="6cf14ac85106cb7c09568a330139d674b55a9c63249023c6fbd2a50d46815f34",
)
IMPORT_PATTERN = re.compile(
    r"import \* as diamondProAmNoseSource from '\./diamondproam_nose\.js\?sha256=[0-9a-f]{64}';")
RADIUS_READ = "noseR: diamondProAmNoseSource.DIAMOND_PROAM_NOSE_LEAF.value_mm / 1000,"


def digest(data):
    return hashlib.sha256(data).hexdigest()


def canonical_sha(value):
    return digest(json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode())


def require(condition, reason):
    if not condition:
        raise ValueError("nose source binding: " + reason)


def load_source(root=ROOT):
    source = json.loads((root / SOURCE_PATH).read_text())
    require(source["identity"] == SOURCE_ID, "not the owner-selected Rasson commit/leaf/receipt")
    leaf, record = source["leaf"], source["record"]
    require(canonical_sha(leaf) == SOURCE_ID["leaf_sha256"], "Rasson CU-09 leaf digest mismatch")
    require(canonical_sha(record) == SOURCE_ID["record_sha256"], "Rasson CU-09 receipt digest mismatch")
    require(leaf["id"] == record["canonical_row"] == SOURCE_ID["leaf"], "receipt names another leaf")
    require(leaf["source"]["tier"] == "MODEL" and leaf["verification"]["replicated"] is True
            and leaf["verification"]["verdict"] == record["verification"]["verdict"] == "CONFIRMED",
            "Rasson radius has no confirmed MODEL replication")
    radius = leaf["value"]["tip_fillet_R_mm"]
    require(isinstance(radius, (int, float)) and not isinstance(radius, bool)
            and math.isfinite(radius) and radius > 0, "radius is not a positive finite measurement")
    return source


def citation(source):
    return dict(doc=CITATION, tier="MODEL", **source["identity"], snapshot=SOURCE_PATH)


def bound_leaves(root=ROOT, law=None):
    source = load_source(root)
    radius, cited = source["leaf"]["value"]["tip_fillet_R_mm"], citation(source)
    leaves, definitions = {}, {}
    for size in SIZES:
        path = root / f"docs/geometry/diamond-proam-{size}-table-definition.json"
        data = json.loads(path.read_text())
        found = [f for f in data["features"] if f["id"] == "CU-11"]
        require(len(found) == 1, size + " requires exactly one CU-11")  # DERIVED: unique canonical leaf.
        leaf = found[0]
        require(leaf["value_mm"] == radius and leaf["source"] == cited
                and leaf.get("provenance", {}).get("tag") == "MODEL",
                size + " CU-11 differs from the unscaled, cited Rasson radius")
        leaves[size], definitions[size] = leaf, dict(path=str(path.relative_to(root)), sha256=digest(path.read_bytes()))
    law = json.loads((root / LAW_PATH).read_text()) if law is None else law
    target = law["targets"]["nose_radius_mm"]
    require(target["value"] == radius and target["tag"] == "MODEL" and target["source"] == cited,
            "cushion law radius differs from the cited Rasson leaf")
    return source, leaves, definitions


def module_bytes(leaves, definitions):
    leaf = leaves["9ft"]
    projected = {key: leaf[key] for key in ("id", "value_mm", "scope", "source")}
    projected.update(tag="MODEL", definition=definitions["9ft"], leaf_sha256=canonical_sha(leaf))
    return ("// Generated by tools/render/d621/plan/nose_source_621.py --write.\n"
            "// MODEL: owner-selected Rasson CU-09 radius only; no profile or scale transfer.\n"
            "export const DIAMOND_PROAM_NOSE_LEAF = Object.freeze(\n"
            + json.dumps(projected, indent=2, ensure_ascii=False) + "\n);\n").encode()


def import_line(module):
    return "import * as diamondProAmNoseSource from './diamondproam_nose.js?sha256=" + digest(module) + "';"


def check_binding(root=ROOT, law=None):
    source, leaves, definitions = bound_leaves(root, law)
    expected = module_bytes(leaves, definitions)
    require((root / MODULE_PATH).read_bytes() == expected, "served leaf is stale; regenerate from CU-11")
    table = (root / TABLE_PATH).read_text()
    require(IMPORT_PATTERN.findall(table) == [import_line(expected)], "table.js leaf import digest is stale")
    require(table.count(RADIUS_READ) == 1, "table.js must read the generated CU-11 leaf exactly once")
    return dict(value_mm=leaves["9ft"]["value_mm"], source=citation(source), definitions=definitions,
                source_sha256=digest((root / SOURCE_PATH).read_bytes()),
                module=dict(path=MODULE_PATH, sha256=digest(expected)),
                station_receipt=source["record"]["evidence_quote"], status="BOUND")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--write", action="store_true")
    action.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.write:
        _, leaves, definitions = bound_leaves()
        module = module_bytes(leaves, definitions)
        table = (ROOT / TABLE_PATH).read_text()
        require(len(IMPORT_PATTERN.findall(table)) == 1, "expected one generated import to update")
        (ROOT / MODULE_PATH).write_bytes(module)
        (ROOT / TABLE_PATH).write_text(IMPORT_PATTERN.sub(import_line(module), table))
    print(json.dumps(check_binding(), indent=2))  # DERIVED: receipt formatting only.


if __name__ == "__main__":
    main()
