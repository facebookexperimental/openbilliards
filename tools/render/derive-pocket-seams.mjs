import * as codec from '../../web/scene/pocket-seam-codec.js';

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const DATA = 'web/scene/diamond-pocket-seams-data.js';
export const PROVENANCE = 'tools/render/fixtures/diamond-pocket-seams-provenance.json';
export const SOURCE_RECORD = 'docs/geometry/diamond-pocket-seams-sources.json';
export const TABLES = ['pool_pro_8ft', 'pool_pro_7ft', 'pool_pro_9ft'];
const sha = value => createHash('sha256').update(value).digest('hex');
const bytes = array => new Uint8Array(array.buffer, array.byteOffset, array.byteLength);
const stamp = /const DIAMOND_SEAM_COMPILER_VERSION = '([0-9a-f]{64})';/g;
const transportStamp = /const CN8_TRANSPORT_SOLVER_VERSION = '([0-9a-f]{64})';/g;
export function sourceIdentity(root = ROOT) {
  const source = name => fs.readFileSync(path.join(root, name), 'utf8');
  const table = source('web/scene/table.js');
  if ([...table.matchAll(stamp)].length !== 1 || [...table.matchAll(transportStamp)].length !== 1) throw new Error('POCKET_SEAM_VERSION_COUNT');
  const normal = table.replace(stamp, "const DIAMOND_SEAM_COMPILER_VERSION = '<generated>';" )
    .replace(transportStamp, "const CN8_TRANSPORT_SOLVER_VERSION = '<generated>';" );
  // The CN8 version is another generated hash of table.js. Omitting only
  // that hash breaks the two-generator cycle; CN8 has its own drift gate.
  const sources = { 'web/scene/table.js:except-two-generated-versions': sha(normal) };
  const roots = ['web/scene/table.js', 'web/scene/cuestick.js', 'web/scene/diamond-pocket-seams.js'];
  const excluded = new Set([DATA]);
  const seen = new Set(), queue = roots.slice();
  while (queue.length) {
    const name = queue.pop();
    if (seen.has(name) || excluded.has(name)) continue;
    seen.add(name);
    const text = source(name);
    if (name !== 'web/scene/table.js') sources[name] = sha(text);
    for (const specifier of new vm.SourceTextModule(text, { identifier: name }).dependencySpecifiers) {
      if (specifier === 'three') queue.push('web/vendor/three.module.min.js');
      else if (specifier.startsWith('.')) queue.push(path.posix.normalize(path.posix.join(path.posix.dirname(name), specifier.replace(/[?#].*$/s, ''))));
      else throw new Error('POCKET_SEAM_UNRECORDED_STATIC_INPUT: ' + name + ' -> ' + specifier);
    }
  }
  for (const name of ['tools/render/derive-pocket-seams.mjs', 'tools/render/compile-pocket-seams.mjs',
    'tools/render/pocket-seam-certification.mjs', 'tools/render/audit-pocket-seams.mjs',
    'tools/render/ghcn8/cpu_table_inputs.mjs', 'tools/render/ghcn8/cn8_emitted_checks.mjs',
    'web/scene/cn8ringtex.js', 'web/dist/pool-wasm/pool_wasm.js']) sources[name] = sha(source(name));
  const ordered = Object.fromEntries(Object.entries(sources).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0));
  return { sha256: sha(JSON.stringify(ordered)), sources: ordered,
    scope: 'Complete builder and paired-cue static dependency graph, runtime leaf, compiler, independent certificate and CPU adapter. Only the two generated table version literals are normalised.',
    input_policy: 'Repository procedural geometry only. No purchased model, measurement file or private saved geometry is a compiler input.' };
}
export function serializeArtifact(artifact) {
  return '// Generated by tools/render/derive-pocket-seams.mjs. Lossless typed-array patches.\n'
    + '// Inputs: repository procedural geometry only. No runtime seam solver.\n'
    + 'export const artifact = ' + JSON.stringify(artifact) + ';\n';
}
export function inputOnlySource(root, name) {
  if (name === 'web/scene/diamond-pocket-seams.js') {
    // Explicit generator boundary, analogous to the CPU transport adapter.
    // Never deployed. It builds the inputs without consuming its output.
    return 'export function validate() {}\nexport function apply() {}\n';
  }
  const source = fs.readFileSync(path.join(root, name), 'utf8');
  return name === 'web/scene/table.js' ? source + '\nexport { frameGeom };\n' : source;
}
function independentIdentity(geometry) {
  return { attributes: Object.fromEntries(Object.keys(geometry.attributes).sort().map(name => {
    const a = geometry.attributes[name]; return [name, { type: a.array.constructor.name, item_size: a.itemSize,
      normalized: a.normalized, length: a.array.length, sha256: sha(bytes(a.array)) }];
  })), index: { type: geometry.index.array.constructor.name, length: geometry.index.count, sha256: sha(bytes(geometry.index.array)) } };
}
export async function compileTable({ root = ROOT, tableId, audit = null, observe = null }) {
  if (!TABLES.includes(tableId)) throw new Error('POCKET_SEAM_COMPILER_SCOPE');
  const loadStart = performance.now();
  const built = await buildTransportInputs({ root, tableId, settle: true, readSource: name => inputOnlySource(root, name) });
  const { G, group, THREE, tableAPI } = built;
  const inputLoadMs = performance.now() - loadStart, inputs = codec.inputIdentity(group, G);
  const names = ['dm-bed-cloth', ...G.pockets.map((p, i) => 'dm-bootcollar-' + (p.corner ? 'c' : 's') + i)];
  const meshes = codec.meshMap(group, names);
  const before = new Map(names.map(name => [name, { geometry: meshes.get(name).geometry,
    snapshot: codec.snapshotGeometry(meshes.get(name).geometry) }]));
  const openings = { corner: tableAPI.pocketOpeningPlan(G, 'corner'), side: tableAPI.pocketOpeningPlan(G, 'side') };
  const compilerStart = performance.now();
  let compiled;
  try {
    compiled = compilePocketClothSeams({ THREE, G, F: tableAPI.frameGeom(G), group, openings,
      pocketAxisFrame: tableAPI.pocketAxisFrame, createCertifier: createPocketSeamCertifier });
  } catch (error) {
    await observe?.({ status: 'COMPILER_REFUSED', tableId, error: { message: error.message, event: error.seamEvent ?? null },
      compiler_ms: performance.now() - compilerStart, inputs, built, before });
    throw error;
  }
  const compilerMs = performance.now() - compilerStart, encodeStart = performance.now();
  const patches = names.map(name => codec.encodePatch(name, before.get(name).snapshot, meshes.get(name).geometry));
  const provenance = {}, emitted = {};
  // Audit the carrier's reconstructed buffers, not the compiler objects.
  // Metadata is separately bound to each output. It is not shipped to the
  // browser and is attached only after an independent SHA-256 comparison.
  for (const patch of patches) {
    const mesh = meshes.get(patch.mesh), compiledGeometry = mesh.geometry;
    const expected = independentIdentity(compiledGeometry);
    const applied = codec.applyPatch({ name: mesh.name, geometry: before.get(mesh.name).geometry }, codec.decodePatch(patch));
    const actual = independentIdentity(applied);
    if (JSON.stringify(expected) !== JSON.stringify(actual)) throw new Error('POCKET_SEAM_CARRIER_BYTE_MISMATCH: ' + mesh.name);
    const metadata = compiledGeometry.userData.pocketSeam;
    provenance[mesh.name] = { output_identity: actual, map: metadata };
    applied.userData.pocketSeam = metadata;
    mesh.geometry = applied; compiledGeometry.dispose(); emitted[mesh.name] = actual;
  }
  const encodeMs = performance.now() - encodeStart;
  await observe?.({ status: 'CARRIER_DECODED', tableId, built, before, inputs, compiled, emitted,
    compiler_ms: compilerMs, input_load_ms: inputLoadMs, encoding_ms: encodeMs });
  const auditResult = await audit?.({ built, before, openings, provenance, emitted, compiled });
  await observe?.({ status: 'TABLE_COMPILED', tableId, built, before, inputs, compiled, emitted, audit: auditResult,
    compiler_ms: compilerMs, input_load_ms: inputLoadMs, encoding_ms: encodeMs });
  if (auditResult && auditResult.status !== 'PASS') throw Object.assign(new Error('POCKET_SEAM_INDEPENDENT_AUDIT_RED'), { audit: auditResult });
  return { entry: { key: codec.signature(G), table_id: tableId, inputs, patches }, provenance,
    audit: auditResult, timing: { input_load_ms: inputLoadMs, compiler_ms: compilerMs, encoding_ms: encodeMs } };
}
export async function generate({ root = ROOT, audit = null, observe = null } = {}) {
  const sources = sourceIdentity(root), entries = [], provenance = {}, results = [];
  const version = [...fs.readFileSync(path.join(root, 'web/scene/table.js'), 'utf8').matchAll(stamp)][0][1];
  if (version !== sources.sha256) throw new Error('POCKET_SEAM_SOURCE_VERSION_DRIFT');
  for (const tableId of TABLES) {
    const row = await compileTable({ root, tableId, audit, observe });
    entries.push(row.entry); provenance[tableId] = row.provenance; results.push({ table_id: tableId, audit: row.audit, timing: row.timing });
  }
  if (sourceIdentity(root).sha256 !== sources.sha256) throw new Error('POCKET_SEAM_SOURCE_CHANGED_DURING_COMPILE');
  const artifact = { schema: codec.SCHEMA, source_version: sources.sha256, entries };
  const module = serializeArtifact(artifact), maps = JSON.stringify({ schema: codec.SCHEMA, source_version: sources.sha256, tables: provenance }) + '\n';
  if (Buffer.byteLength(module) >= 10 * 1024 * 1024 || Buffer.byteLength(maps) >= 30 * 1024 * 1024) throw new Error('POCKET_SEAM_ARTIFACT_SIZE_CAP');
  const record = { ...sources, artifact: { path: DATA, sha256: sha(module), bytes: Buffer.byteLength(module) },
    provenance: { path: PROVENANCE, sha256: sha(maps), bytes: Buffer.byteLength(maps) },
    format: 'Lossless typed-array scalar updates and appended tails, plus indexed replacements of original parent triangles. Base64/word-run byte codec; no quantisation.' };
  return { artifact, module, provenance: maps, sourceRecord: JSON.stringify(record, null, 2) + '\n', results };
}
export function checkIdentity(root = ROOT, readOutput = name => fs.readFileSync(path.join(root, name))) {
  const current = sourceIdentity(root), record = JSON.parse(readOutput(SOURCE_RECORD).toString());
  const version = [...fs.readFileSync(path.join(root, 'web/scene/table.js'), 'utf8').matchAll(stamp)][0][1];
  if (current.sha256 !== version || current.sha256 !== record.sha256
    || JSON.stringify(current.sources) !== JSON.stringify(record.sources)) throw new Error('POCKET_SEAM_SOURCE_IDENTITY_DRIFT');
  for (const item of [record.artifact, record.provenance]) {
    const value = readOutput(item.path);
    if (value.byteLength !== item.bytes || sha(value) !== item.sha256) throw new Error('POCKET_SEAM_ARTIFACT_IDENTITY_DRIFT: ' + item.path);
  }
  return { status: 'PASS_IDENTITY', source_version: version, artifact_bytes: record.artifact.bytes, provenance_bytes: record.provenance.bytes };
}
if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const action = process.argv[2];
  if (action === '--check-identity') console.log(JSON.stringify(checkIdentity(), null, 2));
  else if (action === '--stamp-source') {
    const value = sourceIdentity(), filename = path.join(ROOT, 'web/scene/table.js');
    fs.writeFileSync(filename, fs.readFileSync(filename, 'utf8').replace(stamp,
      "const DIAMOND_SEAM_COMPILER_VERSION = '" + value.sha256 + "';"));
    console.log(value.sha256);
  } else if (action === '--write' || action === '--check') {
    const { auditPocketSeams } = await import('./audit-pocket-seams.mjs');
    const generated = await generate({ audit: auditPocketSeams });
    for (const [name, content] of [[DATA, generated.module], [PROVENANCE, generated.provenance], [SOURCE_RECORD, generated.sourceRecord]]) {
      const filename = path.join(ROOT, name);
      if (action === '--check') {
        if (fs.readFileSync(filename, 'utf8') !== content) throw new Error('POCKET_SEAM_REGENERATION_DRIFT: ' + name);
      } else { fs.mkdirSync(path.dirname(filename), { recursive: true }); fs.writeFileSync(filename, content); }
    }
    console.log(JSON.stringify({ status: action === '--check' ? 'PASS_REGENERATION' : 'GENERATED', results: generated.results }, null, 2));
  } else throw new Error('Use --stamp-source, --check-identity, --write or --check. Generation requires --experimental-vm-modules.');
}
