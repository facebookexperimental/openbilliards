// Bundle the recovery keys only; the table must not import the locale loader.
// Two byte-identical copies are emitted from one source: the app-side copy
// (main.js / settings.js) and the scene-side copy (table.js), so that no
// scene module imports from web/app.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
export const KEYS = ['boot.scene', 'table.preparing', 'error.reloadPage', 'error.reloadMessage', 'error.dismissErrors'];
export function generatedBootCopy(root = ROOT) {
  const en = JSON.parse(fs.readFileSync(path.join(root, 'web/app/locales/en.json'), 'utf8'));
  const defaults = Object.fromEntries(KEYS.map(key => {
    if (typeof en[key] !== 'string') throw new Error('BOOT_COPY_KEY_MISSING: ' + key);
    return [key, en[key]];
  }));
  return [
    '// Generated by tools/render/ghcn8/gen_boot_copy.mjs from the default locale.',
    '// A tiny key fallback, not a locale loader or a new asynchronous boot task.',
    'export const fallback = Object.freeze(' + JSON.stringify(defaults, null, 2) + ');',
    '',
    'export function t(key, params) {',
    '  const translator = globalThis.window?.__i18n;',
    '  if (translator?.keys?.()?.includes(key) && typeof translator.t === "function") {',
    '    return translator.t(key, params);',
    '  }',
    '  const text = fallback[key] ?? key;',
    '  return params ? text.replace(/\\{(\\w+)\\}/g, (match, name) =>',
    '    params[name] === undefined ? match : String(params[name])) : text;',
    '}',
    ''
  ].join('\n');
}
export const TARGETS = Object.freeze(['web/app/locales/boot.js', 'web/scene/cn8-boot-copy.js']);
export function main(argv = process.argv.slice(2)) {
  const source = generatedBootCopy();
  for (const target of TARGETS) {
    const file = path.join(ROOT, target);
    if (argv.includes('--check')) {
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== source) throw new Error('BOOT_COPY_STALE: ' + target);
      console.log('BOOT-COPY OK: ' + target + ' matches the generated defaults');
    } else {
      fs.writeFileSync(file, source);
      console.log('BOOT-COPY generated: ' + target + ' ' + Buffer.byteLength(source) + ' bytes');
    }
  }
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
