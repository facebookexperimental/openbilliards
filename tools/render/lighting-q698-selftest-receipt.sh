# GH-638 / #727 — the GENERATOR of the Q698 detector self-test receipt (ORDER-LIGHT-C2-FIX16 S4(3): the receipt names its generator, the probe's
# last-changing commit and HEAD at run, not "committed at <HEAD>"). Runs the probe's `--detector-selftest` twice — RUN 1 (the anchored self-test)
# and RUN 2 (`--plant-badkey`, the planted negative that must FAIL on the fixture/source cell) — into output/lighting/q698-detector-selftest.log,
# rotating an existing receipt aside under the tag given, and appends ONE chain line. No browser; nothing but node on the probe file.
#   zsh tools/render/lighting-q698-selftest-receipt.sh <rotate-tag>     e.g. fix15
setopt nullglob
set +e
TAG=${1:?rotate tag for the previous receipt, e.g. fix15}
cd "${0:A:h:h:h}" || exit 2
PROBE=tools/render/lighting-q698-probe.mjs
RD=${OB_L41V_RECORD_DIR:-$PWD}   # the record dir, as the verdict driver reads it: the receipt and the chain line land there (a throwaway run points it at a scratch record)
R=$RD/output/lighting/q698-detector-selftest.log
[ -d "$RD/output/lighting" ] || { echo "[selftest-receipt] no record dir $RD/output/lighting"; exit 2; }
[ -f "$PROBE" ] || { echo "[selftest-receipt] no $PROBE"; exit 2; }
[ -f "$R" ] && /usr/local/bin/python3 -c "import os,sys; os.rename(sys.argv[1], sys.argv[1].replace('.log', '.' + sys.argv[2] + '.log'))" "$R" "$TAG"
PS=$(shasum -a 256 "$PROBE" | cut -c1-12)
LAST=$(git log -1 --format='%h %cI' -- "$PROBE" 2>/dev/null || echo 'unknown')
HEADS=$(git rev-parse --short=8 HEAD 2>/dev/null || echo 'unknown')
T0=$(date -u +%FT%TZ)
{
  echo "[q698-detector-selftest] RECEIPT generated by tools/render/lighting-q698-selftest-receipt.sh at $T0 — probe sha $PS; probe last changed in commit $LAST; HEAD at run $HEADS; cwd $PWD"
  echo "[q698-detector-selftest] RUN 1 (source anchor over state()'s two venue branches + all four venue.applied literals + budgetDegradeRecord + fix9State, scanner == engine per literal; the detector cases incl. the degrade record, readability and the unreadable→refusal cell) START $T0"
  node "$PROBE" --detector-selftest; echo "[q698-detector-selftest] RUN 1 rc $?"
  echo "[q698-detector-selftest] RUN 2 (planted bad key — the fixture/source cell MUST fail) START $(date -u +%FT%TZ)"
  node "$PROBE" --detector-selftest --plant-badkey; echo "[q698-detector-selftest] RUN 2 rc $?"
} > "$R" 2>&1
R1=$(grep -oE 'RUN 1 rc [0-9]' "$R" | grep -oE '[0-9]$'); R2=$(grep -oE 'RUN 2 rc [0-9]' "$R" | grep -oE '[0-9]$')
LINE="[chain41] FIX16 detector self-test receipt $(date -u +%FT%TZ): $R (record dir $RD; previous kept as q698-detector-selftest.$TAG.log) — generator tools/render/lighting-q698-selftest-receipt.sh; probe sha $PS; probe last changed in commit $LAST; HEAD at run $HEADS; RUN 1 $(grep -m1 -oE '(PASS|FAIL) [0-9]+/[0-9]+' "$R") rc $R1; RUN 2 (planted bad key) $(grep -oE 'FAIL [0-9]+/[0-9]+ \(planted bad key[^)]*\)' "$R") rc $R2"
echo "$LINE" >> "$RD/output/lighting/chain-land41.log"
echo "$LINE"
[ "$R1" = 0 ] && [ "$R2" = 1 ]
