// gen-stale-scene-fixture.mjs — extract the pre-rename scene (web/scene/table.js as it was at
// 7352fa8ed2acdb401d66251b5ddc9ca245361e3d, the parent of the GH-789 v20 rename commit 6f333d92)
// into web/tools/fixtures/scene-table-stale-7352fa8e.mjs, the only copy of that scene the
// lifecycle suite (test-ballreturn-lifecycle.mjs L80-0 / L80p S3 / L82) reads. The suite never
// calls git: a CI checkout is depth 1, so history is absent there.
//
// The extract holds exactly what the suite reads from the old scene:
//   - the APP_DEFAULT_TABLE_ID declaration (verbatim);
//   - every TABLE_SPECS key, as a key skeleton (the object literal's members, values elided,
//     one `  <key>: {` / `  },` pair each; the computed [SCRIPTED_PIN_TABLE_ID] member kept as written);
//   - every top-level `TABLE_SPECS.<id> = ...` alias assignment, as `TABLE_SPECS.<id> = {};`
//     (the key only; values elided);
//   - resolveBootTableId, bootLegalTableIds, bootClassDefaultTableId (verbatim top-level declarations);
//   - the nested prepareEquipment (verbatim: `  function prepareEquipment(` up to the first `\n  }\n`,
//     the suite's own slice rule), inside a host function so the file parses as a module.
// The file is parse-only: it is read as text, never imported.
//
//   node web/tools/gen-stale-scene-fixture.mjs           write the fixture (needs the source commit)
//   node web/tools/gen-stale-scene-fixture.mjs --check   re-extract and compare byte for byte (exit 1 on a difference)
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const WEB = path.resolve(here, '..');
const SOURCE_SHA = '7352fa8ed2acdb401d66251b5ddc9ca245361e3d';
const SOURCE_PATH = 'web/scene/table.js';
const OUT = path.join(WEB, 'tools', 'fixtures', 'scene-table-stale-7352fa8e.mjs');
const TOP_NAMES = ['resolveBootTableId', 'bootLegalTableIds', 'bootClassDefaultTableId'];
const NESTED = 'prepareEquipment';

const args = process.argv.slice(2);
const known = new Set(['--check']);
for (const a of args) if (!known.has(a)) { console.error(`gen-stale-scene-fixture: unknown argument ${a}`); process.exit(2); }
const CHECK = args.includes('--check');

async function extract() {
  const src = execFileSync('git', ['-C', WEB, 'show', `${SOURCE_SHA}:${SOURCE_PATH}`], { encoding: 'utf8', maxBuffer: 1 << 26 });
  const { parse } = await import('../../tools/render/lib/vendor/acorn/acorn.mjs');
  const ast = parse(src, { ecmaVersion: 'latest', sourceType: 'module' });
  let appDefault = null; let specKeys = null; const aliases = []; const tops = {};
  for (const top of ast.body) {
    const d = top.type === 'ExportNamedDeclaration' ? top.declaration : top;
    if (!d) continue;
    if (d.type === 'VariableDeclaration') {
      for (const v of d.declarations) {
        if (v.id.name === 'APP_DEFAULT_TABLE_ID') appDefault = src.slice(top.start, top.end);
        if (v.id.name === 'TABLE_SPECS') {
          if (v.init?.type !== 'ObjectExpression') throw new Error('TABLE_SPECS is not an object literal');
          specKeys = v.init.properties.map((p) => {
            if (p.type !== 'Property') throw new Error(`TABLE_SPECS member of type ${p.type}`);
            if (p.computed && p.key.type === 'Identifier') return `[${p.key.name}]`;
            if (!p.computed && p.key.type === 'Identifier') return p.key.name;
            throw new Error(`TABLE_SPECS member key ${src.slice(p.key.start, p.key.end)} is neither a name nor a computed name`);
          });
        }
      }
    }
    if (d.type === 'ExpressionStatement' && d.expression.type === 'AssignmentExpression') {
      const l = d.expression.left;
      if (l.type === 'MemberExpression' && !l.computed && l.object.type === 'Identifier' && l.object.name === 'TABLE_SPECS') aliases.push(l.property.name);
    }
    if (d.type === 'FunctionDeclaration' && TOP_NAMES.includes(d.id.name)) {
      if (tops[d.id.name]) throw new Error(`${d.id.name} is declared twice`);
      tops[d.id.name] = src.slice(top.start, top.end);
    }
  }
  if (!appDefault) throw new Error('APP_DEFAULT_TABLE_ID not found');
  if (!specKeys?.length) throw new Error('no TABLE_SPECS keys read');
  for (const n of TOP_NAMES) if (!tops[n]) throw new Error(`${n} not found`);
  const head = `\n  function ${NESTED}(`; const a = src.indexOf(head);
  if (a < 0 || src.indexOf(head, a + 1) >= 0) throw new Error(`nested ${NESTED} is not declared exactly once`);
  const b = src.indexOf('\n  }\n', a);
  if (b < 0) throw new Error(`nested ${NESTED} is unclosed`);
  const nested = src.slice(a + 1, b + 4);
  const out = [
    '// GENERATED by web/tools/gen-stale-scene-fixture.mjs; do not edit (regenerate, then --check).',
    `// Source: git show ${SOURCE_SHA}:${SOURCE_PATH}`,
    `// Source sha256: ${createHash('sha256').update(src).digest('hex')} (${Buffer.byteLength(src)} bytes)`,
    '// A minimal extract of the pre-rename scene for test-ballreturn-lifecycle.mjs (read as text, never imported):',
    '// TABLE_SPECS keys and alias keys with values elided; the boot declarations and prepareEquipment verbatim.',
    '',
    appDefault,
    '',
    'export const TABLE_SPECS = {',
    ...specKeys.flatMap((k) => [`  ${k}: {`, '  },']),
    '};',
    '',
    ...aliases.map((k) => `TABLE_SPECS.${k} = {};`),
    '',
    ...TOP_NAMES.flatMap((n) => [tops[n], '']),
    'function staleSceneHost() {',
    nested,
    '}',
    '',
  ].join('\n');
  parse(out, { ecmaVersion: 'latest', sourceType: 'module' });
  return { out, keys: specKeys.length, aliases: aliases.length };
}

const { out, keys, aliases } = await extract();
if (CHECK) {
  const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
  const same = have === out;
  console.log(`gen-stale-scene-fixture --check: ${path.relative(path.resolve(WEB, '..'), OUT)} ${same ? 'IDENTICAL to' : 'DIFFERS from'} the extract of ${SOURCE_SHA}:${SOURCE_PATH}`
    + ` (committed ${have === null ? 'absent' : `${Buffer.byteLength(have)} bytes sha256 ${createHash('sha256').update(have).digest('hex')}`};`
    + ` extract ${Buffer.byteLength(out)} bytes sha256 ${createHash('sha256').update(out).digest('hex')})`);
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(OUT, out);
console.log(`gen-stale-scene-fixture: wrote ${path.relative(path.resolve(WEB, '..'), OUT)} (${keys} TABLE_SPECS keys, ${aliases} alias keys, ${Buffer.byteLength(out)} bytes)`);
